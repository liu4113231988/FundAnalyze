RBSA = dict(
    window=252,          # 滚动估计窗口（交易日，约 1 年）
    refit=20,            # 重估频率（交易日，约 1 月）
    min_obs=180,         # 窗口内最少有效样本
    l1_ratio=0.5,        # ElasticNet 的 L1 占比
    alpha_grid=(1e-4, 3e-4, 1e-3, 3e-3, 1e-2, 3e-2, 1e-1),  # 由时序CV选
    min_weight=0.01,     # 权重低于此值视为噪声，归零后重新归一
    max_assets=8,        # 稀疏支撑集上限
    equity_ratio=0.90,   # 目标股票仓位（auto_equity=False 时直接作为 Σw 的目标）
    max_rebal=60,        # 滚动重估点上限（超出则均匀抽稀，控制 Web 首屏耗时）
    # ★ 默认开启自适应仓位。固定 0.9 对混合型基金是灾难性的：
    #   实测 163402 / 000001 / 519005 在 Σw=0.9 下窗口内 R² 中位数为 0.000，
    #   而把 Σw 降到各自的实际仓位（0.25~0.30）后 R² 恢复到 0.74~0.85。
    #   根因是强制 Σw=0.9 会让合成基准的波动远超基金本身，残差里混进纯粹的尺度误差。
    auto_equity=True,
    # "local" = beta 不动点给初值 + 邻域细搜并最大化窗口内 R²（默认，4 次拟合/窗口）
    # "beta"  = 只用 beta 不动点（2 次拟合，最快，但估计系统性高估约 25%）
    # "grid"  = equity_grid 全网格最大化 R²（8 次拟合，基准口径，用于复核）
    equity_method="local",
    equity_local_step=0.10,   # local 法的邻域半宽
    equity_grid=(0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.95),
    equity_bounds=(0.20, 1.00),  # 实际仓位的裁剪区间
    equity_iters=2,      # 仅 beta 阶段使用：迭代次数
)

SIGNAL = dict(
    trend_ma=60,         # 趋势均线窗口
    trend_mom=120,       # 趋势动量窗口
    trend_slope=120,     # 斜率回归窗口
    z_short=60,          # 偏离度短期动能窗口
    z_long=252,          # 偏离度标准化窗口（也是中枢窗口）
    kappa=1.0,           # tanh 压缩系数（趋势）
    kappa_z=0.8,         # tanh 压缩系数（估值/偏离）
    w_trend=0.50,        # 趋势通道权重
    w_dev=0.35,          # 相对偏离通道权重
    w_val_pe=0.15,       # 赛道估值通道权重
    # 估值数据的发布滞后（日历日）。乐咕乐股月度 PE 的日期戳是**月末**，
    # 但月末值要到次月初才发布；不设滞后会让估值通道含 1~10 天的前瞻。
    pe_lag_days=10,
    # ---- 波动率目标（风险归一化，不预测方向）
    # mode="target"  : 波动率高则减仓（经典风险平价）→ 实测超额年化 −1.32%
    # mode="inverse" : 波动率高则加仓（波动率择时）  → 实测超额年化 +0.36%、9/14 为正
    # 两者差异说明**风险平价假设在 A 股不成立**：波动率与收益同向，
    # 机械降波动等于系统性放弃收益。
    vol_target_mode="inverse",
    vol_target=0.15,     # 目标年化波动（inverse 模式下用作归一化中枢）
    vol_target_win=60,   # 已实现波动的观测窗口
    vol_target_min=0.30, # 仓位下限（不因波动极低而满仓）
    vol_target_max=1.00, # 仓位上限
    vol_target_rebalance=60,  # 调仓周期（交易日）
    smooth=5,            # 目标仓位 EMA 平滑
    rebalance_band=0.08, # 调仓死区
    # ---- 拟合健康度风险门控（阈值事先固定，不做事后优选）
    health_win_long=504, # R²/TE 中枢窗口（约 2 年）
    health_win_short=504,# 实现 alpha 窗口（约 2 年）
    #   为什么是 2 年而不是 1 年：alpha 的年化标准误 ≈ 年化TE/√(年数)。
    #   1 年窗口下 SE≈6~10%，要判"alpha 显著为负"需要跑输 20% 以上，几乎测不出；
    #   2 年窗口把 SE 压到 ≈4.5%，t=−3 对应跑输 13.5%，才有实际检测能力。
    health_smooth=5,     # 健康分 EMA 平滑
    health_alpha_t=6.0,  # alpha 分量刻度：t=−6 → −1，故离场线 −0.5 对应 t=−3
    #   为什么是 6：alpha 的 t 值本身是 sd≈1 的随机变量，252 日重叠窗口下
    #   全样本 min(t) 轻易到 −1.75（实测）。刻度取 2 会让健康基金也有 8.6%
    #   的时间被判"不健康"——那是在给噪声做交易。刻度 6 意味着只有
    #   "跑输复制组合 3 个标准误"才离场，代价是只抓得住严重的能力钝化。
    health_confirm=10,   # 连续 N 个交易日越过阈值才真正换手（滤掉单日尖峰）
    health_r2_min=0.5,   # 拟合可信的最低 R²：低于此值只**停用门控**，不触发卖出。
    #   R² 低说的是"我的模型解释不了这只基金"（典型成因：固定 0.9 的仓位假设
    #   对混合型基金不成立，合成基准波动被放大 1.5~2 倍），而不是"基金变差了"。
    #   把这两件事混为一谈会对仓位失配的基金永久误卖。
    health_exit=-0.5,    # 任一诊断分项跌破并持续 → 卖出离场
    health_enter=-0.2,   # 健康分回升至此并持续 → 重新买入（迟滞带防反复）
)

