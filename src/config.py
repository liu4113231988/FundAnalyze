# ★ 抓取起点：**固定**，与分析窗口解耦。
#   缓存名里带 start（fund_nav_{code}_{start}_total.csv），若让抓取起点跟着
#   分析窗口滚动，那么每换一次窗口（甚至每天）都会让全部缓存 miss ——
#   在离线/受限网络环境下等于直接拿不到数据。
#   所以：抓取始终用这段固定长区间（同时保证预热期充足），
#   分析时再裁剪到 START_DATE。见 data.fetch_start_for()。
